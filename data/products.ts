export function formatRupiah(amount: number): string {
  return new Intl.NumberFormat('id-ID', {
    style: 'currency',
    currency: 'IDR',
    maximumFractionDigits: 0,
  }).format(amount);
}

export function getProductById(id: string): Product | undefined {
  return INITIAL_PRODUCTS.find((p) => p.id === id);
}

export function getProductsBySeller(sellerName: string, excludeProductId?: string): Product[] {
  return INITIAL_PRODUCTS.filter(
    (p) => p.seller.name.toLowerCase() === sellerName.toLowerCase() && p.id !== excludeProductId
  );
}

export function getAvailableProducts(): Product[] {
  return INITIAL_PRODUCTS.filter((p) => !p.isSold && p.isAvailable);
}
